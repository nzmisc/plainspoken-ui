// Writes app/theme.css: the default theme (lib/theme.ts) and the foundation CSS (lib/foundation.ts),
// so this site's stylesheet is exactly what the registry gives a project.
//
//   node scripts/build-theme.ts           # write it
//   node scripts/build-theme.ts --check   # fail if it is out of date (the build runs this)
import { readFileSync, writeFileSync } from "node:fs";
import { buildTheme, DEFAULT_THEME, themeCss } from "../lib/theme.ts";
import { FOUNDATION_CSS, cssText, spacingTheme } from "../lib/foundation.ts";

const FILE = new URL("../app/theme.css", import.meta.url);

const css = `/*
 * Generated by scripts/build-theme.ts from lib/theme.ts and lib/foundation.ts. Don't edit by hand.
 * The default plainspoken-ui theme in shadcn/ui's token names, plus the control height scale.
 */

${themeCss(buildTheme(DEFAULT_THEME), { fontVars: { sans: "--font-geist", mono: "--font-geist-mono" } })}

${spacingTheme()}

${cssText(FOUNDATION_CSS)}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(FILE, "utf8");
  } catch {}
  if (current !== css) {
    console.error("app/theme.css is out of date: run node scripts/build-theme.ts");
    process.exit(1);
  }
} else {
  writeFileSync(FILE, css);
  console.log("wrote app/theme.css");
}
